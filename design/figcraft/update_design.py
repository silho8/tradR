def frame(key,name,x):
    d.append({'command':'frame.create','as':key,'params':{'name':name,'x':x,'y':1120,'width':390,'height':844,'props':{'fill':'#F7F8F4','cornerRadius':24,'clip':True}}})
def rect(parent,name,x,y,w,h,fill='#FFFFFF',radius=14,stroke=None):
    props={'fill':fill,'cornerRadius':radius}
    if stroke: props.update({'stroke':stroke,'strokeWeight':1})
    d.append({'command':'node.create','params':{'type':'rectangle','name':name,'parent':{'$ref':parent},'x':x,'y':y,'width':w,'height':h,'props':props}})
def txt(parent,name,text,x,y,w,h,size=13,color='#102A43',font='Inter',weight='Regular'):
    d.append({'command':'node.create','params':{'type':'text','name':name,'parent':{'$ref':parent},'text':text,'x':x,'y':y,'width':w,'height':h,'props':{'fontFamily':font,'fontSize':size,'fontStyle':weight,'fill':color,'textAutoResize':'height','lineHeight':'120%'}}})
def line(parent,name,x,y,w,color='#E8ECE6'):
    rect(parent,name,x,y,w,1,color,0)
